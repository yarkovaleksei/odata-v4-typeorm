#!/bin/sh
#
# Точка входа тестового контейнера.
#
# Устанавливает зависимости и передаёт управление переданной команде. Установка вынесена
# сюда, а не в Dockerfile, намеренно: образ тогда не зависит от содержимого package.json
# и не требует пересборки после каждой правки зависимостей — разработчик получает ровно
# то, что записано в текущем yarn.lock.
#
# Скрипт на POSIX sh, а не bash: в slim-образе Node баша может не быть.

set -eu

# --frozen-lockfile: установка обязана соответствовать yarn.lock. Если package.json
# разошёлся с ним, лучше упасть здесь с внятным сообщением, чем молча получить другой
# набор версий и потом гадать, почему тест ведёт себя иначе, чем в CI.
#
# Кэш yarn лежит в томе (см. compose.yaml), поэтому при неизменном lock-файле
# повторный запуск занимает секунды.
echo "==> Установка зависимостей (yarn install --frozen-lockfile)"
yarn install --frozen-lockfile

# Ожидание баз вынесено в compose (`depends_on` + healthcheck), поэтому здесь его нет:
# к моменту старта контейнера PostgreSQL и MySQL уже принимают соединения.

echo "==> $*"
exec "$@"
