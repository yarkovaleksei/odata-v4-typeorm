/**
 * @file Значения полей посетителя для незаданных query options.
 *
 * Незаданная опция даёт не пустую строку, а нейтральное выражение SQL: `where` попадает
 * прямо в `andWhere`, `orderby` — в `addOrderBy`, и пустая строка там была бы синтаксической
 * ошибкой. Заодно эти значения служат признаком «опция не задана»: их сверяет
 * `executeQueryByQueryBuilder` (список колонок SELECT, добавлять ли сортировку),
 * `processIncludes` (какой JOIN строить) и `nestedPageCondition` (что уносить в подзапрос окна).
 *
 * ПОЧЕМУ КОНСТАНТЫ, А НЕ ЛИТЕРАЛЫ ПО МЕСТУ. Сравнений с этими значениями по библиотеке
 * около десятка, и все они строгие. Литерал `'1 = 1'`, записанный где-то как `'1=1'`,
 * не сломает ни сборку, ни линтер: SQL останется корректным, а проверка «опция не задана»
 * молча перестанет срабатывать — то есть в запрос уедет лишний `WHERE`, лишний `ORDER BY`
 * или лишний список колонок.
 */

/**
 * Значения полей `TypeOrmVisitor`, означающие «соответствующая опция в запросе не задана».
 *
 * @example
 * if (odataQuery.select === VISITOR_DEFAULTS.select) {
 *   // $select не задан — выбираем все колонки корня
 * }
 */
export const VISITOR_DEFAULTS = {
  /** `$select` не задан — выбрать все невиртуальные колонки. */
  select: '*',
  /** `$filter` не задан — нейтральное условие, безопасное внутри `AND`. */
  where: '1 = 1',
  /** `$orderby` не задан — `ORDER BY 1`, то есть сортировку добавлять не нужно. */
  orderby: '1',
} as const;
