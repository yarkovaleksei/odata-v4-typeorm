/**
 * @file Запуск точки входа парсера с приведением любой неожиданной ошибки к типизированной.
 *
 * ЗАЧЕМ. `createQuery` и `createFilter` различаются ровно одним — какой функцией разбирать
 * строку (`parseQueryOptions` против `parseFilter`). Всё остальное, включая обработку ошибок,
 * у них совпадало дословно, и обёртка существовала в двух копиях.
 *
 * ЗАЧЕМ САМА ОБЁРТКА. Разбор уже бросает {@link ODataParseError} на всё, что предусмотрел.
 * Страховка нужна для ошибки, которую он не предусмотрел: HTTP-слой обязан в любом случае
 * отличить ошибку клиента от внутреннего сбоя по признаку `isClientError`, а не разбором
 * текста сообщения. Непойманное `TypeError` из середины разбора дало бы `500` на запрос,
 * который на самом деле прислал клиент.
 */
import { ODataError, ODataParseError } from '../errors';
import type { Token } from './token';

/**
 * Разбирает строку указанной точкой входа парсера.
 *
 * @param source - разбираемая строка: query options целиком либо одно выражение фильтра.
 * @param parse - точка входа парсера, которой эту строку скормить.
 * @returns корневой узел дерева.
 *
 * @throws {ODataParseError} строка синтаксически некорректна — либо разбор упал ошибкой,
 *   которую сам не предусмотрел.
 * @throws {ODataUnsupportedError} строка разобрана, но содержит конструкцию вне
 *   поддерживаемого подмножества: такая ошибка уже типизирована и пробрасывается как есть.
 */
export function parseOrThrow(source: string, parse: (source: string) => Token): Token {
  try {
    return parse(source);
  } catch (e) {
    if (e instanceof ODataError) {
      throw e;
    }

    throw new ODataParseError(source, e);
  }
}
