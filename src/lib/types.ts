/**
 * @file Общие типы для входящих HTTP/query параметров и настроек генерации SQL.
 *
 * Значения приходят в основном как строки (как из `req.query` в Express); часть полей
 * перед выполнением запроса приводится к числам/булевым типам (см. `parseQueryParams`).
 */
/**
 * Диалекты SQL, для которых библиотека умеет подбирать реализацию функций OData.
 *
 * Выбирается конкретная SQL-функция — `LENGTH` против `LEN`, `EXTRACT` против `strftime`
 * и так далее. Возможности диалекта, влияющие не на функции, а на форму запроса, живут
 * в `src/lib/dialect`.
 *
 * `'ansi'` — запасной вариант для незнакомого драйвера: берутся наиболее переносимые формы.
 */
export type SqlDialect = 'postgres' | 'mysql' | 'sqlite' | 'mssql' | 'oracle' | 'ansi';

/**
 * Опции компиляции OData в SQL.
 *
 * Значение `alias` служит сразу двум целям, и это важно помнить: помимо префикса колонок оно же
 * используется как ключ поиска метаданных сущности в `executeQueryByQueryBuilder`, поэтому должно
 * совпадать с именем класса сущности либо именем её таблицы.
 */
export interface SqlOptions {
  alias: string;

  /**
   * Как разрешить связь в подзапрос — нужно лямбда-операторам `books/any(b: …)`.
   *
   * Компилятор OData работает со строками SQL и метаданных сущностей не знает: имя таблицы,
   * колонки внешнего ключа и таблицу связей может назвать только слой выполнения. Он же
   * и передаёт сюда эту функцию; `executeQuery` делает это сам.
   *
   * Не передана — лямбда-оператор отвергается `ODataUnsupportedError`. Так бывает при прямом
   * вызове `createFilter` без подключения к базе: имя таблицы взять неоткуда.
   */
  resolveRelation?: RelationResolver;

  /**
   * Какого типа EDM колонка по пути свойства — нужно приведению `cast(x, Edm.String)`.
   *
   * Второй канал метаданных рядом с {@link SqlOptions.resolveRelation} и по тому же принципу:
   * компилятор объявляет потребность, а закрывает её слой выполнения, у которого есть
   * `EntityMetadata`. Сам компилятор знает только имена свойств — решить, тотально ли
   * приведение, он без этого не может.
   *
   * Не передан — `cast` отвергается `ODataUnsupportedError`, как отвергается лямбда при прямом
   * вызове `createFilter` без метаданных. `executeQuery` передаёт функцию сам.
   */
  resolveColumnType?: ColumnTypeResolver;

  /**
   * Выносить ли значения литералов в параметры (`:p0`) вместо подстановки в текст SQL.
   *
   * Выключать стоит только там, где SQL собирают и исполняют вручную и параметры некуда
   * передать. Инлайн литералов — это ровно та поверхность, через которую в запрос попадает
   * пользовательский ввод, поэтому умолчание обратное.
   *
   * @defaultValue `true`
   */
  useParameters?: boolean;

  /**
   * Целевая СУБД. Определяет, какие SQL-функции подставлять для функций OData.
   *
   * Принимается как значение {@link SqlDialect}, так и «сырой» `type` из настроек TypeORM
   * (`'better-sqlite3'`, `'mariadb'`, `'aurora-postgres'`, …) — незнакомые значения
   * приводятся к `'ansi'`.
   *
   * `executeQuery` подставляет его автоматически из подключения; задавать вручную нужно
   * только при прямом вызове `createQuery` / `createFilter`.
   *
   * @defaultValue `'ansi'`
   */
  dialect?: SqlDialect | string;
}

/**
 * Источник строк для подзапроса по связи.
 *
 * @property from - содержимое `FROM` с алиасами таблиц.
 * @property where - условие, связывающее подзапрос с родительской таблицей.
 * @property resolveRelation - как разрешать связи уже от целевой сущности: нужно
 *   вложенным лямбдам, где отсчёт идёт от связанной сущности, а не от корня.
 * @property column - как записать колонку целевой сущности в SQL.
 */
export interface RelationSource {
  from: string;
  where: string;
  resolveRelation: RelationResolver;

  /**
   * Имя свойства → готовое выражение колонки с алиасом подзапроса.
   *
   * Компилятор OData оперирует именами свойств: он не знает ни про `namingStrategy`,
   * ни про правила экранирования драйвера. Во внешнем запросе имя свойства превращает
   * в имя колонки сам TypeORM, но алиас подзапроса ему неизвестен — значит, эту работу
   * должен сделать тот, у кого есть метаданные.
   */
  column: (property: string) => string;
}

/**
 * Разрешает путь связей в источник строк для подзапроса.
 *
 * @param navigation - путь связей от текущей сущности: `['books']`, `['books', 'reviews']`.
 * @param parentAlias - алиас родительской таблицы во внешнем запросе.
 * @param childAlias - имя, под которым связанная таблица должна быть доступна в подзапросе.
 * @returns источник строк либо `undefined`, если связи с таким именем нет.
 */
export type RelationResolver = (
  navigation: readonly string[],
  parentAlias: string,
  childAlias: string
) => RelationSource | undefined;

/**
 * Разрешает путь свойства в примитивный тип EDM.
 *
 * @param propertyPath - путь от текущего уровня: `'name'`, `'author/name'`.
 * @returns имя типа EDM (`'Edm.Int32'`) либо `undefined`, если такого свойства нет или это
 *   связь, а не колонка. `undefined` — это «тип неизвестен», и приведение с ним отвергается:
 *   догадка о типе означала бы догадку о том, может ли `CAST` провалиться.
 */
export type ColumnTypeResolver = (propertyPath: string) => string | undefined;

/**
 * Параметры OData V4 в «сыром» виде, как их обычно передают в query string.
 * Ключи совпадают с именами системных query options OData (`$filter`, `$top`, …).
 *
 * Все поля объявлены строками, потому что тип описывает вход до нормализации — ровно то,
 * что кладёт в `req.query` Express. Числовые и булевы значения появляются только
 * в {@link ParsedQueryParams}.
 *
 * Системные опции OData, которых здесь нет и которые библиотека не поддерживает:
 * `$apply`, `$format`, `$levels`, `$skiptoken`, `$deltatoken`, `$id`, `$schemaversion`.
 */
export interface QueryParams {
  $search?: string;
  $filter?: string;
  $orderby?: string;
  $select?: string;
  $expand?: string;
  $compute?: string;
  $top?: string;
  $skip?: string;
  $count?: string;
}

/**
 * Нормализованные параметры после `parseQueryParams`.
 *
 * `$top` / `$skip` / `$count` строго типизированы и всегда определены (не `undefined`), потому что
 * ими управляет логика пагинации. Остальные опции остаются строками: их значение — это выражения
 * на языке OData, которые всё равно поедут обратно в парсер через `queryToOdataString`.
 *
 * `$search` намеренно опциональный: `undefined` здесь означает «поиск не применять»,
 * и `executeQueryByQueryBuilder` отделяет его до склейки OData-строки.
 */
export type ParsedQueryParams = Pick<
  QueryParams,
  '$search' | '$filter' | '$orderby' | '$select' | '$expand' | '$compute'
> & {
  /**
   * Размер страницы. `undefined` означает «клиент не задавал `$top`» и трактуется как
   * «лимита нет»; `0` — что клиент запросил ровно ноль строк, и это валидный запрос
   * по OData v4 (раздел 11.2.6.4), а не синоним отсутствия лимита.
   */
  $top?: number;
  $skip: number;
  /**
   * Нужен ли счётчик. Отсутствующий в запросе `$count` даёт `false` — так требует
   * OData v4 (раздел 11.2.5.5), и от этого зависит форма ответа: массив против
   * `{ items, count }`.
   */
  $count: boolean;
};
