/**
 * @file Сведения о целевой СУБД: приведение драйвера TypeORM к диалекту и возможности диалекта.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ. Раньше `normalizeDialect` жил внутри `TypeOrmVisitor` как файловая
 * функция. Диалект понадобился второму потребителю — построителю условия вложенной пагинации,
 * которому нужно знать, умеет ли СУБД оконные функции. Копировать список драйверов во второе
 * место нельзя: он разъедется при первом же добавлении драйвера.
 *
 * Модуль намеренно НЕ включён в `src/lib/index.ts`: это внутренняя деталь, а не часть контракта.
 */
import type { SqlDialect } from '../types';

/**
 * Приведение значения `type` из настроек TypeORM к одному из поддерживаемых диалектов.
 *
 * TypeORM различает больше драйверов, чем существует диалектных различий: `mariadb` ведёт себя
 * как `mysql`, `better-sqlite3` — как `sqlite`, облачные варианты Postgres — как обычный Postgres.
 * Незнакомый драйвер сводится к `'ansi'`: там подставляются наиболее переносимые конструкции.
 */
export function normalizeDialect(driver?: string): SqlDialect {
  switch (driver) {
    case 'postgres':
    case 'aurora-postgres':
    case 'cockroachdb':
      return 'postgres';
    case 'mysql':
    case 'mariadb':
    case 'aurora-mysql':
      return 'mysql';
    case 'sqlite':
    case 'better-sqlite3':
    case 'capacitor':
    case 'cordova':
    case 'expo':
    case 'nativescript':
    case 'sqljs':
      return 'sqlite';
    case 'mssql':
      return 'mssql';
    case 'oracle':
      return 'oracle';
    default:
      return 'ansi';
  }
}

/**
 * Можно ли переносить вложенную пагинацию `$expand=books($top=2)` в SQL.
 *
 * Приём один: пронумеровать связанные строки оконной функцией в подзапросе и оставить
 * снаружи только нужный отрезок нумерации (см. `buildNestedPageCondition`). Он требует,
 * чтобы СУБД вычисляла окно ДО того, как применит внешнее условие, — иначе нумерация
 * считается по уже отобранным строкам и страница получается неверной.
 *
 * ПОЧЕМУ ИСКЛЮЧЁН MySQL. Версия 8.4.11 это условие нарушает: она проталкивает внешнее
 * равенство внутрь подзапроса с окном, номер строки всегда получается первым, и условие
 * на страницу оказывается истинным для любой строки — то есть `$top` молча перестаёт
 * действовать. Проверено прогоном во всех формах записи: `EXISTS`, `IN` по паре значений,
 * `IN` по одному ключу с корреляцией и без неё. С литеральными значениями вместо ссылок
 * наружу MySQL считает верно, а в одних формах ошибается, в других нет — то есть поведение
 * зависит от выбранного плана, и полагаться на него нельзя. Молча неверная страница хуже
 * лишних строк, поднятых из базы, поэтому на MySQL срез делает `applyNestedPagination`.
 *
 * ПОЧЕМУ ИСКЛЮЧЁН `'ansi'`. Незнакомый драйвер: оконных функций может не быть вовсе.
 * Их умеют давно (PostgreSQL с 8.4, SQLite с 3.25, MS SQL с 2005, Oracle с 8i), но
 * неверная догадка означает синтаксическую ошибку в каждом запросе с вложенным `$top`.
 *
 * Отключить перенос и там, где он разрешён, можно опцией `nestedPaginationInSql: false`.
 */
export function supportsNestedPagePushdown(dialect: SqlDialect): boolean {
  return dialect !== 'mysql' && dialect !== 'ansi';
}
