/**
 * @file Типы, специфичные для слоя `executeQuery`: опции вызова и форма ответа при `$count=true`.
 */
import type { ObjectLiteral } from 'typeorm';

/** Опции выполнения запроса. */
export interface ExecuteQueryOptions {
  /**
   * SQL-алиас корневой сущности — префикс колонок в генерируемом SQL.
   *
   * Может быть любым: метаданные сущности берутся из самого `SelectQueryBuilder`
   * (`expressionMap.mainAlias.metadata`), а не по имени алиаса. Привычный TypeORM-стиль
   * `createQueryBuilder('u')` работает.
   *
   * Для `SelectQueryBuilder` можно не задавать — подставится его собственный корневой алиас.
   * Для `Repository` задавайте всегда: иначе построитель получит пустое имя.
   *
   * Запасной путь на случай, когда у построителя нет метаданных (например корень —
   * подзапрос): поиск через `connection.getMetadata(alias)`, и там алиас уже обязан
   * совпадать с именем сущности или таблицы.
   */
  alias?: string;

  /**
   * Верхняя граница `$top`. Запрос с бо́льшим значением обрезается до `maxTop`.
   *
   * Без неё клиент одним запросом вытягивает таблицу целиком, а вместе с `$expand` —
   * ещё и умножает объём выборки. Для публичного API задавайте всегда.
   *
   * @defaultValue без ограничения
   */
  maxTop?: number;

  /**
   * Белый список полей, доступных клиенту через `$select`, `$filter` и `$orderby`.
   *
   * Без него клиент может запросить любое поле сущности, включая служебные.
   * Имена сравниваются с путями свойств (`'name'`, `'author/name'`).
   *
   * @defaultValue разрешены все поля
   */
  allowedFields?: readonly string[];

  /**
   * Белый список связей, доступных через `$expand` и пути в `$filter` / `$orderby`.
   *
   * Проверяется имя связи на каждом уровне вложенности: для `$expand=books($expand=reviews)`
   * в списке должны быть и `books`, и `reviews`.
   *
   * @defaultValue разрешены все связи
   */
  allowedExpands?: readonly string[];

  /**
   * Поля, по которым работает `$search`: пути свойств от корня.
   *
   * Не задано — поиск идёт по всем скалярным колонкам корневой сущности: текстовым
   * по подстроке, числовым по точному равенству. Это удобно, но на публичном API опасно
   * и медленно: клиент перебором строки поиска выясняет содержимое полей, которые
   * вы не собирались показывать, и каждый запрос сканирует таблицу целиком.
   *
   * Путь может идти через связи: `'author/name'`. Такое поле компилируется в `EXISTS`,
   * поэтому число корневых строк не меняется и `$top` продолжает означать то же самое.
   *
   * @defaultValue все скалярные колонки корня
   *
   * @example
   * executeQuery(repo, req.query, { alias: 'Book', searchFields: ['title', 'author/name'] });
   */
  searchFields?: readonly string[];

  /**
   * Как `$search` сравнивает текст.
   *
   * `'like'` (по умолчанию) ищет подстроку: находит середину слова, но не пользуется
   * индексами — каждый запрос сканирует таблицу целиком.
   *
   * `'fulltext'` переключает сравнение на полнотекстовый поиск СУБД:
   * `to_tsvector @@ plainto_tsquery` в PostgreSQL, `MATCH … AGAINST` в MySQL. Ищет слова
   * целиком, зато опирается на индекс. На SQLite и MS SQL режим молча остаётся `'like'`:
   * там полнотекстовый поиск требует отдельной виртуальной таблицы или каталога.
   *
   * **В MySQL колонка обязана входить в индекс `FULLTEXT`** — иначе СУБД отвергнет запрос.
   * В PostgreSQL запрос выполнится и без индекса, просто медленно; индекс создаётся как
   * `CREATE INDEX … USING GIN (to_tsvector('<язык>', <колонка>))` с тем же языком,
   * что в `searchLanguage`.
   *
   * Структуру выражения (`AND` / `OR` / `NOT`, скобки) в обоих режимах разбирает сама
   * библиотека, поэтому `$search` ведёт себя одинаково на всех СУБД.
   *
   * @defaultValue `'like'`
   */
  searchMode?: 'like' | 'fulltext';

  /**
   * Конфигурация полнотекстового поиска PostgreSQL: `'simple'`, `'english'`, `'russian'`.
   *
   * Определяет словарь словоформ: с `'simple'` найдётся только точное слово, с `'russian'` —
   * все его формы. Должна совпадать с языком в индексе, иначе индекс не используется.
   * Имя подставляется в SQL как есть и потому проверяется по шаблону `[a-z_][a-z0-9_]*`.
   *
   * Имеет смысл только при `searchMode: 'fulltext'` на PostgreSQL.
   *
   * @defaultValue `'simple'`
   */
  searchLanguage?: string;

  /**
   * Выполнять ли вложенную пагинацию (`$expand=books($top=2)`) средствами SQL.
   *
   * По умолчанию страницу связи вырезает оконная функция в условии соединения: из базы
   * поднимается только запрошенная страница. Выключение возвращает прежнее поведение —
   * связанные строки приходят целиком, а срез делается над деревом сущностей.
   *
   * Выключать имеет смысл ровно в двух случаях: СУБД без оконных функций, которую библиотека
   * не распознала как таковую (MySQL 5.7, MariaDB 10.1 — обе сняты с поддержки), либо
   * неудачный план запроса на конкретных данных. Незнакомый драйвер и так обрабатывается
   * срезом в памяти — для него опция ничего не меняет.
   *
   * @defaultValue `true`
   */
  nestedPaginationInSql?: boolean;
}

/**
 * Ответ при `$count=true`: страница данных и общее число строк по текущим фильтрам
 * (без учёта `$top` / `$skip`).
 *
 * Форма ответа ПО УМОЛЧАНИЮ — обычный массив: по OData v4 (раздел 11.2.5.5) отсутствующий
 * `$count` означает `false`. Объект возвращается, только если клиент явно попросил счётчик.
 * Поэтому возвращаемый тип `executeQuery` — объединение `T[] | GetManyResponse<T>`,
 * и на стороне вызова его нужно сузить.
 *
 * @example
 * const result = await executeQuery(repo, req.query, { alias: 'User' });
 * const items = Array.isArray(result) ? result : result.items;
 */
export interface GetManyResponse<T extends ObjectLiteral> {
  items: T[];
  count: number;
}
