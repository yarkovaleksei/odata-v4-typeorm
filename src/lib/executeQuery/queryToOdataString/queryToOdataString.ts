/**
 * @file Сериализация объекта параметров обратно в формат, ожидаемый `odata-v4-parser.query`.
 */
import type { ParsedQueryParams, QueryParams } from '../../types';

/**
 * Символы, которые `encodeURI` оставляет как есть, хотя для парсера OData они значимы.
 *
 * `#` начинает фрагмент URI, `?` — строку запроса; встретив любой из них внутри строкового
 * литерала, парсер считает, что выражение кончилось, и отвечает `Unexpected character`.
 * Остальное `encodeURI` либо кодирует сам, либо парсер переваривает: проверено, что
 * `&`, `+`, `=`, `%` и пробел внутри литерала работают без экранирования.
 */
const RESERVED_OUTSIDE_ODATA_GRAMMAR: Readonly<Record<string, string>> = {
  '#': '%23',
  '?': '%3F',
};

/**
 * Кодирует значение параметра так, чтобы его пережил парсер OData.
 *
 * `encodeURI` выбран вместо `encodeURIComponent` сознательно: последний закодировал бы
 * `$`, `(`, `)`, `,` и `'` — то есть саму грамматику OData, и конструкция
 * `$expand=CreatedBy($select=Id)` перестала бы разбираться. Взамен приходится
 * доэкранировать `#` и `?` вручную.
 */
function encodeValue(value: unknown): string {
  return encodeURI(String(value)).replace(
    /[#?]/g,
    (character) => RESERVED_OUTSIDE_ODATA_GRAMMAR[character]
  );
}

/**
 * Преобразует объект параметров запроса в OData-строку.
 *
 * Шаг нужен потому, что `odata-v4-parser` принимает на вход только строку query options, а на
 * уровне приложения параметры приходят объектом (`req.query`). Отбираются только ключи,
 * начинающиеся с `$`, — всё прикладное (`page`, `lang`, токены) отбрасывается и в парсер не попадает.
 * Значения `null` / `undefined` пропускаются, чтобы не породить `$filter=undefined`.
 *
 * ВЫБОР `encodeURI` ВМЕСТО `encodeURIComponent` — сознательный компромисс, а не недосмотр:
 *
 * - `encodeURIComponent` закодировал бы `$`, `(`, `)`, `,` и `'`, то есть саму грамматику OData.
 *   Конструкция `$expand=CreatedBy($select=Id),CreatedBy($select=FirstName)` превратилась бы
 *   в `%24expand%3D...` и перестала разбираться.
 * - `encodeURI` эти символы сохраняет, но пропускает `#` и `?` — их приходится
 *   доэкранировать вручную (см. {@link encodeValue}).
 *
 * Прогон по символам показал, что доэкранирования требуют ровно эти два: `&`, `+`, `=`, `%`
 * и пробел внутри строкового литерала парсер принимает как есть.
 *
 * @param query - объект с параметрами запроса (например, `{ $search: 'hello', $top: 5 }`)
 * @returns строка вида `$search=hello&$top=5` или пустая строка, если подходящих параметров нет
 *
 * @example
 * queryToOdataString({ $top: 5, $filter: "name eq 'Ann'", page: 2 });
 * // → "$top=5&$filter=name%20eq%20'Ann'"   (ключ page отброшен)
 */
export const queryToOdataString = (query: ParsedQueryParams | QueryParams): string => {
  // Преобразуем объект в массив пар [ключ, значение]
  return (
    Object.entries(query)
      /**
       * Оставляем только параметры, начинающиеся с "$" и имеющие значимое значение,
       * то есть не null и не undefined.
       */
      .filter(([key, value]) => key.startsWith('$') && value != null)
      /**
       * Формируем "$ключ=значение". Первый символ `$` отрезается перед кодированием и
       * приписывается обратно вручную — иначе `encodeURI` оставил бы его как есть, но приём
       * зафиксирован явно, чтобы поведение не зависело от таблицы неэкранируемых символов.
       *
       * Значение проходит через `encodeValue`: он доэкранирует `#` и `?`, которые
       * `encodeURI` пропускает, а парсер OData принимает за конец выражения.
       */
      .map(([key, value]) => `$${encodeURI(key.slice(1))}=${encodeValue(value)}`)
      // Объединяем все части через "&"
      .join('&')
  );
};
