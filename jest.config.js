/**
 * Конфигурация Jest.
 *
 * `TEST_DB` выбирает СУБД для интеграционных тестов: `sqlite` (по умолчанию), `postgres`
 * или `mysql`. Для внешних баз меняются две вещи:
 *
 * 1. `globalSetup` создаёт схему один раз до старта воркеров;
 * 2. `maxWorkers: 1` — база одна на всех, и параллельные воркеры дрались бы за данные:
 *    `beforeEach` одного очищал бы таблицы, пока другой из них читает.
 *
 * Для SQLite ничего этого не нужно: `:memory:` даёт каждому воркеру собственную базу,
 * поэтому прогон остаётся параллельным и быстрым.
 *
 * Часовой пояс принудительно ставится в UTC — см. комментарий ниже.
 */
// Часовой пояс фиксируется до создания воркеров, и они его наследуют.
//
// Колонка с датой объявлена без часового пояса, но драйверы обращаются с ней по-разному:
// SQLite сохраняет момент в UTC, PostgreSQL — локальные составляющие. Без общей зоны
// проверки `hour(registeredAt) eq 8` давали разный результат на разных СУБД и на машинах
// разработчиков с разными настройками.
process.env.TZ = 'UTC';

const isExternalDatabase = Boolean(process.env.TEST_DB) && process.env.TEST_DB !== 'sqlite';

module.exports = {
  rootDir: 'src',
  preset: 'ts-jest',
  setupFilesAfterEnv: ['./test/setup/setup.ts'],

  // Покрытие считается только по публикуемому коду: фикстуры и обвязка тестов сами
  // по себе ничего не гарантируют, а их присутствие в отчёте размывало бы цифру.
  collectCoverageFrom: ['lib/**/*.ts', '!lib/**/*.test.ts'],

  // Не в `src/coverage`, как по умолчанию: отчёт — не исходный код.
  coverageDirectory: '<rootDir>/../coverage',

  /**
   * Пороги подобраны по факту (замер 2026-09-06: 98.5% операторов, 96.0% ветвей,
   * 99.3% функций, 98.5% строк) с запасом около двух пунктов. Ставить их вплотную
   * к текущему значению нельзя — тогда порог ломался бы от любой мелочи вроде добавленной
   * проверки аргумента, и его начали бы двигать не глядя. Запас же оставляет место обычной
   * правке, но не даёт незаметно добавить непокрытый модуль.
   *
   * Ветви — исключение: у них запас меньше пункта. Именно они дольше всего оставались
   * слабым местом (85% против 95% у остальных метрик), и держать их на 95 — решение
   * сознательное: незакрытая ветка условия и есть тот случай, когда запрос молча
   * возвращает не те данные.
   *
   * Считается порог только на SQLite (`yarn test:coverage`). На PostgreSQL и MySQL часть
   * блоков размечена `skipOn`, и там цифра заведомо ниже — матричные джобы поэтому гоняют
   * `test:unit` без покрытия.
   *
   * Пофайловый минимум нужен отдельно от общего: без него новый файл вообще без тестов
   * почти не сдвигает средние цифры и проходит незамеченным — а это ровно тот случай,
   * ради которого порог и вводится.
   */
  coverageThreshold: {
    global: { statements: 96, branches: 95, functions: 97, lines: 96 },
    'src/lib/**/*.ts': { statements: 80, lines: 80 },
  },

  ...(isExternalDatabase ? { globalSetup: './test/setup/globalSetup.ts', maxWorkers: 1 } : {}),
};
